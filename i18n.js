window.ohcT = function ohcT(key) {
  const dict = window.OHC_I18N[window.ohcLang] || window.OHC_I18N.en;
  if (dict[key] != null) return dict[key];
  const fallback = window.OHC_I18N.en;
  return fallback[key] != null ? fallback[key] : key;
};

window.ohcVal = function ohcVal(englishValue) {
  if (!englishValue) return "";
  return window.ohcT("val" + englishValue);
};
